import numpy as np
import matplotlib.pyplot as plt

# Number of random samples
N = 100000

# -------------------------------
# 1. UNIFORM NOISE
# -------------------------------

# PDF-based generation using inverse CDF
a, b = 0, 1
u = np.random.rand(N)
uniform_pdf = a + (b - a) * u

# Built-in function
uniform_builtin = np.random.uniform(a, b, N)


# -------------------------------
# 2. GAUSSIAN NOISE
# -------------------------------

mean = 0
sigma = 1

# PDF-based generation using Box-Muller method
u1 = np.random.rand(N)
u2 = np.random.rand(N)

gaussian_pdf = mean + sigma * np.sqrt(-2 * np.log(u1)) * np.cos(2 * np.pi * u2)

# Built-in function
gaussian_builtin = np.random.normal(mean, sigma, N)


# -------------------------------
# 3. ERLANG NOISE
# -------------------------------

k = 5
theta = 1

# PDF-based generation (sum of k exponential variables)
erlang_pdf = np.zeros(N)

for i in range(k):
    u = np.random.rand(N)
    erlang_pdf += -theta * np.log(u)

# Built-in function (Gamma distribution)
erlang_builtin = np.random.gamma(k, theta, N)


# -------------------------------
# 4. EXPONENTIAL NOISE
# -------------------------------

scale = 1

# PDF-based generation using inverse CDF
u = np.random.rand(N)
exponential_pdf = -scale * np.log(1 - u)

# Built-in function
exponential_builtin = np.random.exponential(scale, N)


# -------------------------------
# 5. RAYLEIGH NOISE
# -------------------------------

rayleigh_sigma = 1

# PDF-based generation using inverse CDF
u = np.random.rand(N)
rayleigh_pdf = rayleigh_sigma * np.sqrt(-2 * np.log(1 - u))

# Built-in function
rayleigh_builtin = np.random.rayleigh(rayleigh_sigma, N)


# -------------------------------
# DISPLAY HISTOGRAMS
# -------------------------------

distributions = [
    ("Uniform Noise", uniform_pdf, uniform_builtin),
    ("Gaussian Noise", gaussian_pdf, gaussian_builtin),
    ("Erlang Noise", erlang_pdf, erlang_builtin),
    ("Exponential Noise", exponential_pdf, exponential_builtin),
    ("Rayleigh Noise", rayleigh_pdf, rayleigh_builtin)
]

plt.figure(figsize=(14, 18))

for i, (name, pdf_data, builtin_data) in enumerate(distributions):

    # PDF-based histogram
    plt.subplot(5, 2, 2*i + 1)
    plt.hist(pdf_data, bins=50, density=True)
    plt.title(name + " (PDF Method)")
    plt.xlabel("Noise Value")
    plt.ylabel("Probability")

    # Built-in histogram
    plt.subplot(5, 2, 2*i + 2)
    plt.hist(builtin_data, bins=50, density=True)
    plt.title(name + " (Built-in Method)")
    plt.xlabel("Noise Value")
    plt.ylabel("Probability")

plt.tight_layout()
plt.show()