import tensorflow as tf
import numpy as np
import pandas as pd

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score
)

results = []

# Function to calculate performance metrics
def evaluate_model(model, X_test, y_test, name):

    predictions = model.predict(X_test, verbose=0)

    predicted_labels = np.argmax(predictions, axis=1)

    accuracy = accuracy_score(y_test, predicted_labels)

    precision = precision_score(
        y_test, predicted_labels,
        average='macro', zero_division=0
    )

    recall = recall_score(
        y_test, predicted_labels,
        average='macro', zero_division=0
    )

    f1 = f1_score(
        y_test, predicted_labels,
        average='macro', zero_division=0
    )

    results.append({
        "Model": name,
        "Accuracy": accuracy,
        "Precision": precision,
        "Recall": recall,
        "F1 Score": f1
    })

    print("\n", name)
    print("Accuracy:", round(accuracy, 4))
    print("Precision:", round(precision, 4))
    print("Recall:", round(recall, 4))
    print("F1 Score:", round(f1, 4))


# Evaluate custom CNN
evaluate_model(model, X_test, y_test, "Custom CNN")

from tensorflow.keras.applications import VGG16, MobileNetV2, ResNet50
from tensorflow.keras.applications.vgg16 import preprocess_input as vgg_preprocess
from tensorflow.keras.applications.mobilenet_v2 import preprocess_input as mobile_preprocess
from tensorflow.keras.applications.resnet50 import preprocess_input as resnet_preprocess
from tensorflow.keras import layers, models

# Prepare image preprocessing
X_train_raw = X_train * 255.0
X_val_raw = X_val * 255.0
X_test_raw = X_test * 255.0


# Function to build transfer learning model
def build_transfer_model(base_model):

    base_model.trainable = False

    model = models.Sequential([
        layers.Input(shape=(64, 64, 3)),
        base_model,
        layers.GlobalAveragePooling2D(),
        layers.Dense(128, activation='relu'),
        layers.Dropout(0.5),
        layers.Dense(3, activation='softmax')
    ])

    model.compile(
        optimizer='adam',
        loss='sparse_categorical_crossentropy',
        metrics=['accuracy']
    )

    return model


# List of transfer learning models
transfer_models = [
    ("VGG16", VGG16, vgg_preprocess),
    ("MobileNet", MobileNetV2, mobile_preprocess),
    ("ResNet50", ResNet50, resnet_preprocess)
]


# Train each model
for name, architecture, preprocess in transfer_models:

    print("\nTraining", name)

    # Load pretrained model
    base = architecture(
        weights='imagenet',
        include_top=False,
        input_shape=(64, 64, 3)
    )

    # Build model
    transfer_model = build_transfer_model(base)

    # Preprocess images
    train_data = preprocess(X_train_raw.copy())
    val_data = preprocess(X_val_raw.copy())
    test_data = preprocess(X_test_raw.copy())

    # Early stopping
    early_stop = tf.keras.callbacks.EarlyStopping(
        monitor='val_loss',
        patience=3,
        restore_best_weights=True
    )

    # Train model
    transfer_model.fit(
        train_data,
        y_train,
        epochs=10,
        batch_size=32,
        validation_data=(val_data, y_val),
        callbacks=[early_stop],
        verbose=1
    )

    # Evaluate model
    evaluate_model(
        transfer_model,
        test_data,
        y_test,
        name
    )

    # Release resources
    del transfer_model
    del base
    tf.keras.backend.clear_session()

print("\nAll Transfer Learning Models Completed!")

