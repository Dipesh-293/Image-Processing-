import numpy as np
import tensorflow as tf
from tensorflow.keras import layers, models

# 1. Initialize random 3x3 matrix
matrix = np.random.randint(0, 10, (3, 3))
print("Original Matrix:\n", matrix)

# 2. Padding (P=1)
padded = np.pad(matrix, 1, mode='constant')
print("\nPadded Matrix:\n", padded)

# 3. Convolution
kernel = np.array([
    [1, 0, -1],
    [1, 0, -1],
    [1, 0, -1]
])

output = np.zeros((3, 3))

for i in range(3):
    for j in range(3):
        output[i, j] = np.sum(
            padded[i:i+3, j:j+3] * kernel
        )

print("\nConvolution Output:\n", output)

# 4. Activation functions
relu = np.maximum(output, 0)
sigmoid = 1 / (1 + np.exp(-np.clip(output, -50, 50)))

print("\nReLU Output:\n", relu)
print("\nSigmoid Output:\n", sigmoid)

# 5. Max Pooling and Min Pooling
max_pool = np.max(output[:2, :2])
min_pool = np.min(output[:2, :2])

print("\nMax Pooling:", max_pool)
print("Min Pooling:", min_pool)

# 6. Global Average Pooling
gap = np.mean(output)
print("\nGlobal Average Pooling:", gap)

# 7. Flattening
flatten = output.flatten()
print("\nFlatten Output:\n", flatten)

# 8. Dense Layer
dense = layers.Dense(4)
dense_output = dense(flatten.reshape(1, -1))
print("\nDense Layer Output:\n", dense_output.numpy())

# 9. Batch Normalization
bn = layers.BatchNormalization()
bn_output = bn(dense_output, training=True)
print("\nBatch Normalization:\n", bn_output.numpy())

# 10. Dropout
drop = layers.Dropout(0.5)
drop_output = drop(bn_output, training=True)
print("\nDropout Output:\n", drop_output.numpy())

