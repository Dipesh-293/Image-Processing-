import cv2
import numpy as np
import matplotlib.pyplot as plt
from google.colab import files

# Upload image
uploaded = files.upload()
filename = list(uploaded.keys())[0]

# Read image
img = cv2.imread(filename)

# Convert image to RGB for displaying
img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

# Take filter size from user
size = int(input("Enter filter size (odd number): "))

if size < 3 or size % 2 == 0:
    raise ValueError("Filter size must be an odd number >= 3")

# Take padding method
print("\nPadding methods:")
print("1. Zero Padding")
print("2. Replication Padding")
print("3. Reflection Padding")

choice = int(input("Enter padding choice (1/2/3): "))

padding = {
    1: cv2.BORDER_CONSTANT,
    2: cv2.BORDER_REPLICATE,
    3: cv2.BORDER_REFLECT
}

if choice not in padding:
    raise ValueError("Invalid padding choice")

border = padding[choice]

# Select filter
print("\nSelect Filter:")
print("1. Averaging Filter")
print("2. Weighted Filter")
print("3. Gaussian Filter")

filter_choice = int(input("Enter choice (1/2/3): "))

# Apply selected filter
if filter_choice == 1:

    # Averaging Filter
    result = cv2.blur(img, (size, size),
                      borderType=border)
    title = "Averaging Filter"

elif filter_choice == 2:

    # Weighted Filter: h(x,y) = max(|x|, |y|)
    center = size // 2

    x, y = np.mgrid[-center:center+1, -center:center+1]

    kernel = np.maximum(np.abs(x), np.abs(y)).astype(float)

    # Normalize kernel
    kernel = kernel / np.sum(kernel)

    result = cv2.filter2D(img, -1, kernel,
                          borderType=border)
    title = "Weighted Filter"

elif filter_choice == 3:

    # Gaussian Filter
    sigma = float(input("Enter Gaussian sigma: "))

    result = cv2.GaussianBlur(
        img,
        (size, size),
        sigmaX=sigma,
        borderType=border
    )
    title = "Gaussian Filter"

else:
    raise ValueError("Invalid filter choice")

# Display original and smoothed images
plt.figure(figsize=(12, 5))

plt.subplot(1, 2, 1)
plt.imshow(img)
plt.title("Original Image")
plt.axis("off")

plt.subplot(1, 2, 2)
plt.imshow(result)
plt.title(title)
plt.axis("off")

plt.show()