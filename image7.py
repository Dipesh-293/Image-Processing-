import cv2
import numpy as np
import matplotlib.pyplot as plt
from google.colab import files

# Upload image
uploaded = files.upload()
filename = list(uploaded.keys())[0]

# Read image
img = cv2.imread(filename)

# Convert BGR to RGB
img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

# Convert image to grayscale
gray = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)


# 1. LAPLACIAN FILTER

laplacian = cv2.Laplacian(gray, cv2.CV_64F)

# Sharpen image
laplacian = np.uint8(np.clip(gray - laplacian, 0, 255))


# 2. SOBEL EDGE DETECTOR

sobel_x = cv2.Sobel(gray, cv2.CV_64F, 1, 0, ksize=3)
sobel_y = cv2.Sobel(gray, cv2.CV_64F, 0, 1, ksize=3)

sobel = np.sqrt(sobel_x**2 + sobel_y**2)

sobel = np.uint8(np.clip(sobel, 0, 255))


# 3. CANNY EDGE DETECTOR

canny = cv2.Canny(gray, 100, 200)


# 4. UNSHARP MASKING

# Apply Gaussian blur (5x5, sigma=3)
blur = cv2.GaussianBlur(gray, (5, 5), 3)

# Subtract blurred image from original
mask = cv2.subtract(gray, blur)

# Add mask to original image
unsharp = cv2.add(gray, mask)


# DISPLAY ALL RESULTS

plt.figure(figsize=(15, 10))

plt.subplot(2, 3, 1)
plt.imshow(gray, cmap='gray')
plt.title("Original Image")
plt.axis('off')

plt.subplot(2, 3, 2)
plt.imshow(laplacian, cmap='gray')
plt.title("Laplacian Sharpening")
plt.axis('off')

plt.subplot(2, 3, 3)
plt.imshow(sobel, cmap='gray')
plt.title("Sobel Edge Detection")
plt.axis('off')

plt.subplot(2, 3, 4)
plt.imshow(canny, cmap='gray')
plt.title("Canny Edge Detection")
plt.axis('off')

plt.subplot(2, 3, 5)
plt.imshow(unsharp, cmap='gray')
plt.title("Unsharp Masking")
plt.axis('off')

plt.tight_layout()
plt.show()