uploaded = files.upload()
filename = list(uploaded.keys())[0]

# Read grayscale image
img = cv2.imread(filename, 0)

# Take window sizes from user
smin = int(input("Enter initial window size (odd number): "))
smax = int(input("Enter maximum window size (odd number): "))

if smin < 3 or smin % 2 == 0:
    raise ValueError("Initial size must be odd and >= 3")

if smax < smin or smax % 2 == 0:
    raise ValueError("Maximum size must be odd and >= initial size")

# Add salt and pepper noise
def add_noise(image):
    noisy = image.copy()
    amount = 0.05

    total = int(amount * image.size)

    # Salt noise
    coords = (
        np.random.randint(0, image.shape[0], total),
        np.random.randint(0, image.shape[1], total)
    )
    noisy[coords] = 255

    # Pepper noise
    coords = (
        np.random.randint(0, image.shape[0], total),
        np.random.randint(0, image.shape[1], total)
    )
    noisy[coords] = 0

    return noisy

noisy = add_noise(img)


# Normal Median Filter
median = cv2.medianBlur(noisy, smin)


# Adaptive Median Filter
def adaptive_median(image, smin, smax):

    h, w = image.shape
    pad = smax // 2

    padded = np.pad(image, pad, mode='reflect')

    output = np.zeros_like(image)

    for i in range(h):
        for j in range(w):

            zxy = padded[i + pad, j + pad]
            size = smin

            while size <= smax:

                r = size // 2

                window = padded[
                    i + pad - r : i + pad + r + 1,
                    j + pad - r : j + pad + r + 1
                ]

                zmin = np.min(window)
                zmax = np.max(window)
                zmed = np.median(window)

                # Stage A
                A1 = zmed - zmin
                A2 = zmed - zmax

                if A1 > 0 and A2 < 0:

                    # Stage B
                    B1 = zxy - zmin
                    B2 = zxy - zmax

                    if B1 > 0 and B2 < 0:
                        output[i, j] = zxy
                    else:
                        output[i, j] = zmed

                    break

                else:
                    size += 2

            else:
                output[i, j] = zmed

    return output


adaptive = adaptive_median(noisy, smin, smax)


# Calculate PSNR
def calculate_psnr(original, filtered):

    mse = np.mean((original.astype(float) -
                   filtered.astype(float)) ** 2)

    if mse == 0:
        return float('inf')

    return 10 * np.log10((255 ** 2) / mse)


psnr_noisy = calculate_psnr(img, noisy)
psnr_median = calculate_psnr(img, median)
psnr_adaptive = calculate_psnr(img, adaptive)


# Print PSNR values
print("\nPSNR Comparison")
print("-----------------------")
print("Noisy Image:", psnr_noisy, "dB")
print("Median Filter:", psnr_median, "dB")
print("Adaptive Median:", psnr_adaptive, "dB")


