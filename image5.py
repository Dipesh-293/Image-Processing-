import cv2
import matplotlib.pyplot as plt
from google.colab import files
from skimage.exposure import match_histograms

# Upload input image and reference image
uploaded = files.upload()

# Select uploaded images
names = list(uploaded.keys())

input_img = cv2.imread(names[0], 0)
reference_img = cv2.imread(names[1], 0)

# Perform histogram matching
matched = match_histograms(input_img, reference_img)

# Convert to uint8
matched = matched.clip(0, 255).astype('uint8')

# Display images
plt.figure(figsize=(15, 5))

plt.subplot(1, 3, 1)
plt.imshow(input_img, cmap='gray')
plt.title("Input Image")
plt.axis('off')

plt.subplot(1, 3, 2)
plt.imshow(reference_img, cmap='gray')
plt.title("Reference Image")
plt.axis('off')

plt.subplot(1, 3, 3)
plt.imshow(matched, cmap='gray')
plt.title("Histogram Matched Image")
plt.axis('off')

plt.show()