import cv2
import numpy as np
import matplotlib.pyplot as plt
from scipy.ndimage import uniform_filter
from google.colab import files

# Upload image
uploaded = files.upload()
filename = list(uploaded.keys())[0]

# Read grayscale image
img = cv2.imread(filename, 0)

# Convert image to float
img = img.astype(np.float32) / 255.0

# Take filter size from user
size = int(input("Enter window size (3 or 5): "))

if size not in [3, 5]:
    raise ValueError("Enter only 3 or 5")

# Generate Gaussian noise
noise_sigma = 0.05
gaussian_noise = np.random.normal(0, noise_sigma, img.shape)
gaussian_img = np.clip(img + gaussian_noise, 0, 1)

# Generate Speckle noise
speckle_sigma = 0.2
speckle_noise = np.random.normal(0, speckle_sigma, img.shape)
speckle_img = np.clip(img + img * speckle_noise, 0, 1)


# Wiener Filter
def wiener_filter(image, window, noise_var):

    local_mean = uniform_filter(image, size=window)

    local_square = uniform_filter(image**2, size=window)

    local_var = np.maximum(local_square - local_mean**2, 0)

    result = local_mean + (
        np.maximum(local_var - noise_var, 0) /
        (local_var + 1e-10)
    ) * (image - local_mean)

    return np.clip(result, 0, 1)


# Apply all four filters
def apply_filters(noisy_img, noise_type):

    # Convert to uint8
    temp = (noisy_img * 255).astype(np.uint8)

    # Wiener filter
    if noise_type == "Gaussian":
        noise_var = noise_sigma**2
    else:
        noise_var = speckle_sigma**2 * np.mean(img**2)

    wiener = wiener_filter(noisy_img, size, noise_var)

    # Median filter
    median = cv2.medianBlur(temp, size)

    # Gaussian filter
    gaussian = cv2.GaussianBlur(temp, (size, size), 0)

    # Bilateral filter
    bilateral = cv2.bilateralFilter(
        temp, size, 75, 75
    )

    return [
        wiener,
        median.astype(float) / 255,
        gaussian.astype(float) / 255,
        bilateral.astype(float) / 255
    ]


# Process Gaussian noise
gaussian_results = apply_filters(gaussian_img, "Gaussian")

# Process Speckle noise
speckle_results = apply_filters(speckle_img, "Speckle")


# Display results
titles = [
    "Wiener Filter",
    "Median Filter",
    "Gaussian Filter",
    "Bilateral Filter"
]

plt.figure(figsize=(15, 12))

# First row: Gaussian noise
images1 = [img, gaussian_img] + gaussian_results
names1 = ["Original", "Gaussian Noise"] + titles

